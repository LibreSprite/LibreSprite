// C/C++ char array format implemented in script.
//
// Loaded at startup by the app_boot event (///listen app_boot) and
// registers the "C Array" format for the c/h/cpp/hpp extensions. Saving
// a file with one of those extensions shows a dialog (profile, byte
// order, frame layout, declaration, name) and writes the pixels as a
// char array in a C source file; opening such a file reads the array
// back (the LS-ARRAY tag carries the layout metadata).
//
// A profile is the export contract: the pixel encoding plus whatever
// the target platform expects around it (endianness, headers, palette,
// declaration). v1 ships the raw pixel profiles; later profiles
// (Arduboy, CHGame, ...) are table entries with their own converters.
//
// Output (per-frame layout; the single layout puts all frames in one
// array named "name"):
//   // Generated by LibreSprite (c_array.js)
//   /* LS-ARRAY v1 profile=rgb565 endian=be w=16 h=16 frames=2 layout=perframe */
//   const unsigned char name_0[] = { 0x00, ... };
//   const unsigned char name_1[] = { ... };
//
// Command line (the file comes before --script so it is open when the
// script runs; --set values override the stored settings):
//   libresprite --batch sprite.ase --set out=ship.c --script c_array.js
//   libresprite --batch sprite.ase --set profile=RGB565 \
//               --set endian=Little-endian --set out=ship.c --script c_array.js

file.registerFormat({
  name: "C Array",
  extensions: "c,h,cpp,hpp",
  load: true,
  save: true,
});

// --- profiles ---
//
// toBytes converts the RGBA intermediate (w*h*4) to the array bytes;
// fromBytes is the inverse (it always expands back to RGBA). bpp is the
// bytes per pixel; later bit-packed profiles use bits/packing instead.

const PROFILES = {
  rgba: {
    label: "RGBA",
    bpp: 4,
    toBytes: function (rgba) { return rgba; },
    fromBytes: function (bytes) { return bytes; },
  },
  rgb: {
    label: "RGB",
    bpp: 3,
    toBytes: function (rgba, w, h) {
      const out = new Uint8Array(w * h * 3);
      for (let p = 0; p < w * h; p++) {
        const i = p * 4;
        out[p * 3] = rgba[i];
        out[p * 3 + 1] = rgba[i + 1];
        out[p * 3 + 2] = rgba[i + 2];
      }
      return out;
    },
    fromBytes: function (bytes, w, h) {
      const out = new Uint8Array(w * h * 4);
      for (let p = 0; p < w * h; p++) {
        const i = p * 3;
        out[p * 4] = bytes[i];
        out[p * 4 + 1] = bytes[i + 1];
        out[p * 4 + 2] = bytes[i + 2];
        out[p * 4 + 3] = 255;
      }
      return out;
    },
  },
  rgb565: {
    label: "RGB565",
    bpp: 2,
    endian: "option",
    toBytes: function (rgba, w, h, endian) {
      const out = new Uint8Array(w * h * 2);
      const le = endian === "le";
      for (let p = 0; p < w * h; p++) {
        const i = p * 4;
        const v = ((rgba[i] >> 3) << 11) |
                  ((rgba[i + 1] >> 2) << 5) |
                  (rgba[i + 2] >> 3);
        out[p * 2] = le ? v & 0xff : v >> 8;
        out[p * 2 + 1] = le ? v >> 8 : v & 0xff;
      }
      return out;
    },
    fromBytes: function (bytes, w, h, endian) {
      const out = new Uint8Array(w * h * 4);
      const le = endian === "le";
      for (let p = 0; p < w * h; p++) {
        const i = p * 2;
        const v = le ? bytes[i] | (bytes[i + 1] << 8)
                     : (bytes[i] << 8) | bytes[i + 1];
        const r = v >> 11, g = (v >> 5) & 0x3f, b = v & 0x1f;
        out[p * 4] = (r << 3) | (r >> 2);
        out[p * 4 + 1] = (g << 2) | (g >> 4);
        out[p * 4 + 2] = (b << 3) | (b >> 2);
        out[p * 4 + 3] = 255;
      }
      return out;
    },
  },
};

// --- options ---
//
// The widget ids double as storage keys (the widgets persist their
// values under them), so a headless run reuses the last GUI settings
// and --set overrides both.

const OPT_KEYS = ["profile", "endian", "frames", "decl"];
const DEFAULTS = {
  profile: "RGBA",
  endian: "Big-endian",
  frames: "One array (all frames)",
  decl: "const unsigned char",
};

function isProfileLabel(label) {
  for (const id in PROFILES)
    if (PROFILES[id].label === label)
      return true;
  return false;
}

// The stored option values, validated against the dialog options.
function readStored() {
  for (const k of OPT_KEYS)
    storage.load(k);
  const profile = storage.get("profile");
  const endian = storage.get("endian");
  const frames = storage.get("frames");
  return {
    profile: isProfileLabel(profile) ? profile : DEFAULTS.profile,
    endian: (endian === "Big-endian" || endian === "Little-endian")
            ? endian : DEFAULTS.endian,
    frames: (frames === "One array (all frames)" ||
             frames === "One array per frame")
            ? frames : DEFAULTS.frames,
    decl: String(storage.get("decl") || DEFAULTS.decl),
  };
}

// The export options: the stored values plus the name derived from the
// target file (a stored name would be stale when the file changes).
function readOptions(path) {
  const s = readStored();
  if (!/^[ -~]+$/.test(s.decl))
    throw new Error("the declaration must be printable ASCII");
  let profile = "rgba";
  for (const id in PROFILES)
    if (PROFILES[id].label === s.profile)
      profile = id;
  return {
    profile: profile,
    endian: s.endian === "Little-endian" ? "le" : "be",
    perFrame: s.frames === "One array per frame",
    decl: s.decl,
    name: deriveName(path),
  };
}

// A C identifier from the target file name (basename without extension;
// other characters become _, a leading digit gets a _ prefix).
function deriveName(path) {
  let name = String(path).replace(/\\/g, "/");
  name = name.slice(name.lastIndexOf("/") + 1);
  name = name.replace(/\.[^.]*$/, "");
  name = name.replace(/[^A-Za-z0-9_]/g, "_");
  if (!name)
    name = "image";
  if (/^[0-9]/.test(name))
    name = "_" + name;
  return name;
}

// --- save codec ---

// The frame's pixels as a dense RGBA buffer (w*h*4). The save payload
// is in the sprite's native format (script_file_format.cpp): "RGBA"
// (4B), "GRAY" (1B, no alpha) or "INDEXED" (1B + palette).
function toRgba(frame, w, h) {
  const n = w * h;
  const out = new Uint8Array(n * 4);
  const d = frame.data;
  if (frame.format === "RGBA") {
    out.set(d);
  } else if (frame.format === "GRAY") {
    for (let p = 0; p < n; p++) {
      out[p * 4] = d[p];
      out[p * 4 + 1] = d[p];
      out[p * 4 + 2] = d[p];
      out[p * 4 + 3] = 255;
    }
  } else if (frame.format === "INDEXED") {
    const pal = frame.palette;
    for (let p = 0; p < n; p++) {
      // Palette entries are 32-bit colors, red in the low byte.
      const c = pal[d[p]];
      out[p * 4] = c & 0xff;
      out[p * 4 + 1] = (c >> 8) & 0xff;
      out[p * 4 + 2] = (c >> 16) & 0xff;
      out[p * 4 + 3] = (c >> 24) & 0xff;
    }
  } else {
    throw new Error("unsupported frame format: " + frame.format);
  }
  return out;
}

// The LS-ARRAY tag: the metadata the loader parses. layout records the
// array arrangement (one array holding all frames, or one per frame).
function tagString(opts, w, h, nFrames) {
  let t = "LS-ARRAY v1 profile=" + opts.profile;
  if (PROFILES[opts.profile].endian)
    t += " endian=" + opts.endian;
  t += " w=" + w + " h=" + h + " frames=" + nFrames +
       " layout=" + (opts.perFrame ? "perframe" : "single");
  return "/* " + t + " */";
}

// 16 hex bytes per line, with a trailing comma (valid in C99+).
function emitHex(bytes) {
  let s = "";
  for (let i = 0; i < bytes.length; i++) {
    if (i > 0)
      s += (i % 16 === 0) ? "\n  " : " ";
    s += "0x" + (bytes[i] < 16 ? "0" : "") + bytes[i].toString(16) + ",";
  }
  return s;
}

// ASCII text to file bytes (the generated source is ASCII-only).
function textToBytes(s) {
  const out = new Uint8Array(s.length);
  for (let i = 0; i < s.length; i++)
    out[i] = s.charCodeAt(i);
  return out;
}

// The C source for the frames, as file bytes. Single mode concatenates
// all frames into one array; per-frame mode emits one array per frame.
function encodeFrames(frames, opts) {
  const prof = PROFILES[opts.profile];
  const w = frames[0].width, h = frames[0].height;
  const n = frames.length;

  const encoded = [];
  let total = 0;
  for (let i = 0; i < n; i++) {
    encoded.push(prof.toBytes(toRgba(frames[i], w, h), w, h, opts.endian));
    total += encoded[i].length;
  }

  const parts = [
    "// Generated by LibreSprite (c_array.js)",
    tagString(opts, w, h, n),
    "",
  ];
  const emitArray = (bytes, name) => {
    parts.push(opts.decl + " " + name + "[] = {");
    parts.push("  " + emitHex(bytes));
    parts.push("};");
  };
  if (opts.perFrame) {
    for (let i = 0; i < n; i++) {
      if (i > 0)
        parts.push("");
      emitArray(encoded[i], opts.name + "_" + i);
    }
  } else {
    const all = new Uint8Array(total);
    let off = 0;
    for (let i = 0; i < n; i++) {
      all.set(encoded[i], off);
      off += encoded[i].length;
    }
    emitArray(all, opts.name);
  }
  parts.push("");
  return textToBytes(parts.join("\n"));
}

// format_save: encode the frames and reply with the file bytes. In the
// GUI the export dialog is shown while the codec waits for its reply
// (the app keeps pumping the UI loop meanwhile); headless uses the
// stored settings. The interval re-arms the 2s codec watchdog while
// the dialog is open (a user reading it takes longer than the window).
async function formatSave(id, path, frames) {
  const wd = setInterval(() => file.resetWatchdog(id), 1000);
  try {
    const opts = app.isHeadless ? readOptions(path)
                                : await showExportDialog(path);
    file.onSave(id, encodeFrames(frames, opts));
  } catch (err) {
    file.onSaveError(id, String(err));
  } finally {
    clearInterval(wd);
  }
}

// --- export dialog ---
//
// Resolves with the options on Export, rejects on Cancel. The promise
// is settled by the <id>_click events through dialogState.

let dialogState = null;

function showExportDialog(path) {
  return new Promise((resolve, reject) => {
    if (dialogState) {
      reject(new Error("another export is in progress"));
      return;
    }
    const s = readStored();

    const dlg = app.createDialog("c_array_export");
    dialogState = {dlg: dlg, path: path, resolve: resolve, reject: reject};

    dlg.title = "Export C-Array";
    dlg.canClose = false; // Export/Cancel are the only exits

    dlg.addLabel("Profile:", "profile-label");
    const profW = dlg.addDropDown("profile");
    for (const id in PROFILES)
      profW.addOption(PROFILES[id].label);
    profW.value = s.profile;
    dlg.addBreak();

    dlg.addLabel("Byte order (565):", "endian-label");
    const endianW = dlg.addDropDown("endian");
    endianW.addOption("Big-endian");
    endianW.addOption("Little-endian");
    endianW.value = s.endian;
    dlg.addBreak();

    dlg.addLabel("Frames:", "frames-label");
    const framesW = dlg.addDropDown("frames");
    framesW.addOption("One array (all frames)");
    framesW.addOption("One array per frame");
    framesW.value = s.frames;
    dlg.addBreak();

    dlg.addLabel("Declaration:", "decl-label");
    const declW = dlg.addEntry("", "decl");
    declW.value = s.decl;
    dlg.addBreak();

    dlg.addLabel("Name:", "name-label");
    const nameW = dlg.addEntry("", "name");
    nameW.value = deriveName(path);
    dlg.addBreak();

    dlg.addButton("Export", "export");
    dlg.addButton("Cancel", "cancel");
  });
}

function onExportClick() {
  if (!dialogState)
    return;
  const st = dialogState;
  dialogState = null;
  st.dlg.close();
  // Persist the settings so a command line run can reuse them.
  for (const k of OPT_KEYS)
    storage.save(k);
  try {
    st.resolve(readOptions(st.path));
  } catch (err) {
    st.reject(err);
  }
}

function onCancelClick() {
  if (!dialogState)
    return;
  const st = dialogState;
  dialogState = null;
  st.dlg.close();
  st.reject(new Error("Export canceled"));
}

// --- load codec ---

// File bytes to a JS string (1:1 byte-to-char; the files are ASCII).
function bytesToText(bytes) {
  const chars = new Array(bytes.length);
  for (let i = 0; i < bytes.length; i++)
    chars[i] = bytes[i];
  let s = "";
  for (let i = 0; i < chars.length; i += 8192)
    s += String.fromCharCode.apply(null, chars.slice(i, i + 8192));
  return s;
}

// Find and parse the LS-ARRAY tag; returns {tag, end} or throws.
function parseTag(text) {
  const m = text.match(/\/\*\s*LS-ARRAY v1\b([\s\S]*?)\*\//);
  if (!m)
    throw new Error("not a C-Array file (no LS-ARRAY v1 tag)");
  const tag = {};
  for (const tok of m[1].trim().split(/\s+/)) {
    const eq = tok.indexOf("=");
    if (eq > 0)
      tag[tok.slice(0, eq)] = tok.slice(eq + 1);
  }
  return {tag: tag, end: m.index + m[0].length};
}

// Parse n array initializers in order, starting at pos (hex or decimal
// numbers; anything else inside the braces is skipped).
function parseArrays(text, pos, n) {
  const arrays = [];
  for (let i = 0; i < n; i++) {
    const start = text.indexOf("{", pos);
    if (start < 0)
      throw new Error("frame " + (i + 1) + ": missing array initializer");
    let depth = 0, end = -1;
    for (let j = start; j < text.length; j++) {
      if (text[j] === "{")
        depth++;
      else if (text[j] === "}") {
        depth--;
        if (depth === 0) {
          end = j;
          break;
        }
      }
    }
    if (end < 0)
      throw new Error("frame " + (i + 1) + ": unterminated array initializer");

    const nums = [];
    const re = /0[xX][0-9a-fA-F]+|\d+/g;
    let m;
    while ((m = re.exec(text.slice(start + 1, end))))
      nums.push(parseInt(m[0], (m[0][1] === "x" || m[0][1] === "X") ? 16 : 10));
    arrays.push(nums);
    pos = end + 1;
  }
  return arrays;
}

// format_load: parse the file text and reply with the frames. Every
// profile expands back to RGBA (the load descriptor the app accepts).
function formatLoad(id, data) {
  try {
    const text = bytesToText(data);
    const parsed = parseTag(text);
    const tag = parsed.tag;

    const prof = PROFILES[tag.profile];
    if (!prof)
      throw new Error("unknown profile in LS-ARRAY tag: " + tag.profile);
    const w = parseInt(tag.w, 10);
    const h = parseInt(tag.h, 10);
    const n = parseInt(tag.frames, 10);
    if (!w || !h || !n)
      throw new Error("bad dimensions in LS-ARRAY tag");

    let endian;
    if (prof.endian) {
      if (tag.endian !== "be" && tag.endian !== "le")
        throw new Error("missing or bad endian in LS-ARRAY tag");
      endian = tag.endian;
    }

    const want = w * h * prof.bpp;
    const layout = tag.layout;
    if (layout !== "single" && layout !== "perframe")
      throw new Error("bad layout in LS-ARRAY tag");
    // Single layout: one array holding all frames; perframe: one array
    // per frame.
    const nArrays = (layout === "single") ? 1 : n;
    const wantEach = (layout === "single") ? want * n : want;
    const arrays = parseArrays(text, parsed.end, nArrays);
    for (let i = 0; i < nArrays; i++) {
      if (arrays[i].length !== wantEach)
        throw new Error("array " + (i + 1) + ": expected " + wantEach +
                        " bytes, found " + arrays[i].length);
    }
    const frames = [];
    for (let i = 0; i < n; i++) {
      const src = (layout === "single")
        ? new Uint8Array(arrays[0].slice(i * want, (i + 1) * want))
        : new Uint8Array(arrays[i]);
      frames.push({
        width: w,
        height: h,
        format: "RGBA",
        data: prof.fromBytes(src, w, h, endian),
      });
    }
    file.onLoad(id, {frames: frames});
  } catch (err) {
    file.onLoadError(id, String(err));
  }
}

// --- event handler ---

function onEvent(name, id, path, payload) {
  if (name === "format_save")
    app.critical(async () => formatSave(id, path, payload));
  else if (name === "format_load")
    app.critical(() => formatLoad(id, payload));
  else if (name === "export_click")
    onExportClick();
  else if (name === "cancel_click")
    onCancelClick();
  else if (name === "c_array_export_close")
    // The window was closed some other way: treat it as a cancel.
    onCancelClick();
}
setEventHandler(onEvent);

// Command line export: the sprite opened on the command line is saved
// with the stored settings. Runs on the --script pass (the app_boot
// pass has no document open yet).
if (app.isHeadless && app.activeSprite) {
  storage.load("out");
  const out = storage.get("out");
  if (out)
    sprite.saveAs(String(out), true);
}
